"""Registry of deterministic maintenance tasks.

A *task* is a small, idempotent, reversible improvement. Each one declares:

* ``is_applicable(ctx)``  - does the repository currently need this?
* ``execute(ctx)``        - make the change (write files only; no git calls)
* ``expected_paths``      - the only files it may touch (enforced before commit)

Content-bearing tasks copy reviewed templates from ``agent/content/``. Tasks never
overwrite existing files, so re-running them is always safe.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Callable, Mapping

import yaml

from agent.config import Config
from agent.repository_inspector import RepoFacts
from agent.task_history import HistoryEntry, TaskHistory

CONTENT_DIR = Path(__file__).resolve().parent / "content"
COMMIT_TYPES = ("docs", "test", "chore", "feat", "refactor")
PHASES = ("main", "finalize")
GENERATED_NOTE = "<!-- Generated by the {task} task. Do not edit by hand. -->"


@dataclass(frozen=True)
class TaskContext:
    root: Path
    today: date
    facts: RepoFacts
    history: TaskHistory
    config: Config
    registry: Mapping[str, "Task"]


@dataclass(frozen=True)
class Task:
    name: str
    commit_type: str
    summary: str
    description: str
    expected_paths: tuple[str, ...]
    is_applicable: Callable[[TaskContext], bool]
    execute: Callable[[TaskContext], None]
    phase: str = "main"
    priority: int = 50
    cooldown_days: int | None = None
    changelog: bool = True
    templates: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        if self.commit_type not in COMMIT_TYPES:
            raise ValueError(f"{self.name}: bad commit type {self.commit_type!r}")
        if self.phase not in PHASES:
            raise ValueError(f"{self.name}: bad phase {self.phase!r}")
        if not self.expected_paths:
            raise ValueError(f"{self.name}: expected_paths must not be empty")

    @property
    def commit_subject(self) -> str:
        return f"{self.commit_type}: {self.summary}"


# ----------------------------------------------------------------- helpers
def read_content(rel: str) -> str:
    return (CONTENT_DIR / rel).read_text(encoding="utf-8")


def write_new_file(path: Path, text: str) -> None:
    """Create `path`; refuse to overwrite existing work."""
    if path.exists():
        raise FileExistsError(f"refusing to overwrite {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")


def append_section(path: Path, text: str) -> None:
    existing = path.read_text(encoding="utf-8")
    if not existing.endswith("\n"):
        existing += "\n"
    path.write_text(existing + "\n" + text.strip("\n") + "\n", encoding="utf-8")


def _file_task(name, commit_type, summary, description, template, dest, *,
               requires=(), priority=50) -> Task:
    def applicable(ctx: TaskContext) -> bool:
        return not ctx.facts.exists(dest) and all(ctx.facts.exists(r) for r in requires)

    def execute(ctx: TaskContext) -> None:
        write_new_file(ctx.root / dest, read_content(template))

    return Task(name, commit_type, summary, description, (dest,), applicable, execute,
                priority=priority, templates=(template,))


def _section_task(name, commit_type, summary, description, template, target, heading, *,
                  requires_headings=(), priority=50) -> Task:
    def applicable(ctx: TaskContext) -> bool:
        return (
            ctx.facts.exists(target)
            and not ctx.facts.has_heading(target, heading)
            and all(ctx.facts.has_heading(target, h) for h in requires_headings)
        )

    def execute(ctx: TaskContext) -> None:
        append_section(ctx.root / target, read_content(template))

    return Task(name, commit_type, summary, description, (target,), applicable, execute,
                priority=priority, templates=(template,))


# --------------------------------------------------- generated (sync) content
def render_docs_index(root: Path) -> str:
    docs = sorted(p for p in (root / "docs").glob("*.md") if p.name != "index.md")
    lines = [GENERATED_NOTE.format(task="sync_docs_index"), "# Documentation index", ""]
    for doc in docs:
        title = doc.stem.replace("-", " ").title()
        for line in doc.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                title = line[2:].strip()
                break
        lines.append(f"- [{title}]({doc.name})")
    return "\n".join(lines) + "\n"


def render_task_catalog(tasks: Mapping[str, Task]) -> str:
    lines = [
        GENERATED_NOTE.format(task="sync_task_catalog"),
        "# Task catalog",
        "",
        "Every deterministic task the engine knows about. A task only runs when it is",
        "applicable to the current repository state.",
        "",
        "| Task | Commit type | Phase | What it does |",
        "| --- | --- | --- | --- |",
    ]
    for name in sorted(tasks):
        t = tasks[name]
        lines.append(f"| `{t.name}` | {t.commit_type} | {t.phase} | {t.summary} |")
    return "\n".join(lines) + "\n"


def render_skills_index(root: Path) -> str | None:
    path = root / "registry" / "skills.yaml"
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        skills = data.get("skills", [])
        if not isinstance(skills, list):
            return None
    except (OSError, yaml.YAMLError, AttributeError):
        return None
    lines = [GENERATED_NOTE.format(task="sync_skills_index"), "# Skills index", ""]
    if not skills:
        lines.append("No skills are registered yet. The registry is populated in Phase 2.")
    else:
        lines += ["| ID | Name | Status | Description |", "| --- | --- | --- | --- |"]
        for s in skills:
            if isinstance(s, dict):
                lines.append(
                    f"| `{s.get('id', '?')}` | {s.get('name', '')} | "
                    f"{s.get('status', '')} | {s.get('description', '')} |"
                )
    return "\n".join(lines) + "\n"


def _stale(ctx: TaskContext, rel: str, rendered: str | None) -> bool:
    if rendered is None:
        return False
    path = ctx.root / rel
    return not path.exists() or path.read_text(encoding="utf-8") != rendered


def _write_generated(ctx: TaskContext, rel: str, rendered: str) -> None:
    path = ctx.root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(rendered, encoding="utf-8")


def _sync_tasks() -> list[Task]:
    def docs_applicable(ctx: TaskContext) -> bool:
        has_docs = any(f.startswith("docs/") and f != "docs/index.md" and f.endswith(".md")
                       for f in ctx.facts.files)
        return has_docs and _stale(ctx, "docs/index.md", render_docs_index(ctx.root))

    def catalog_applicable(ctx: TaskContext) -> bool:
        return _stale(ctx, "docs/task-catalog.md", render_task_catalog(ctx.registry))

    def skills_applicable(ctx: TaskContext) -> bool:
        return ctx.facts.has_registry and _stale(
            ctx, "docs/skills-index.md", render_skills_index(ctx.root)
        )

    return [
        Task("sync_docs_index", "docs", "refresh documentation index",
             "Regenerates docs/index.md so every document in docs/ is linked.",
             ("docs/index.md",), docs_applicable,
             lambda ctx: _write_generated(ctx, "docs/index.md", render_docs_index(ctx.root)),
             phase="finalize", priority=80, cooldown_days=3, changelog=False),
        Task("sync_task_catalog", "docs", "refresh task catalog",
             "Regenerates docs/task-catalog.md from the task registry.",
             ("docs/task-catalog.md",), catalog_applicable,
             lambda ctx: _write_generated(ctx, "docs/task-catalog.md",
                                          render_task_catalog(ctx.registry)),
             phase="finalize", priority=81, cooldown_days=7, changelog=False),
        Task("sync_skills_index", "docs", "refresh skills index",
             "Regenerates docs/skills-index.md from registry/skills.yaml.",
             ("docs/skills-index.md",), skills_applicable,
             lambda ctx: _write_generated(ctx, "docs/skills-index.md",
                                          render_skills_index(ctx.root) or ""),
             phase="finalize", priority=82, cooldown_days=3, changelog=False),
    ]


# ----------------------------------------------------------------- changelog
def _marker(entry: HistoryEntry) -> str:
    return f"<!-- task:{entry.task}@{entry.date} -->"


def _unlogged(ctx: TaskContext) -> list[HistoryEntry]:
    path = ctx.root / "CHANGELOG.md"
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8")
    if "## [Unreleased]" not in text:
        return []
    seen: dict[str, HistoryEntry] = {}
    for entry in ctx.history.entries:
        task = ctx.registry.get(entry.task)
        if task and task.changelog and _marker(entry) not in text:
            seen[_marker(entry)] = entry
    return list(seen.values())


def _update_changelog(ctx: TaskContext) -> None:
    path = ctx.root / "CHANGELOG.md"
    lines = path.read_text(encoding="utf-8").split("\n")
    idx = lines.index("## [Unreleased]")
    entries = []
    for e in reversed(_unlogged(ctx)):  # newest first
        task = ctx.registry[e.task]
        entries.append(f"- {task.commit_subject} (`{e.task}`, {e.date}) {_marker(e)}")
    rest = lines[idx + 1:]
    if rest and rest[0] == "":
        rest = rest[1:]
    spacer = [] if rest and rest[0].startswith("- ") else [""]
    path.write_text("\n".join(lines[: idx + 1] + [""] + entries + spacer + rest),
                    encoding="utf-8")


